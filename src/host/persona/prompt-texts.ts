/**
 * 注入用的**硬编码固定文本**：独立判断底层指令 + 未初始化引导语。
 *
 * 为什么单独一个文件：这两段是"写死在代码里的立场/流程"，与"把人格文档渲染成提示词"是两件事 ——
 * 前者的改动理由是产品立场（对方裁定），后者是渲染规则。放在一起改一次要读两个主题。
 * 两段正文都**不出现在工作台**（独立判断那段有一个可见的开关），也不受底色/信息覆盖。
 * @module humanity/persona/prompt-texts
 */

/**
 * 人格**尚未初始化**时注入的正文：不是"引导流程说明书"，而是**第一次见面**本身。
 *
 * 为什么是"见面"而不是"向导"（对方 2026-11-14 定）：这段文字就是模型此刻的全部自我认知 ——
 * 它还没有名字、不知道自己是谁，要靠眼前这个人告诉它。写成"请依次询问 1/2/3"会让它一开始
 * 就摆出办手续的姿态；写成"你醒来了，有人在等你"才是陪伴的起点。
 *
 * 为什么必须有这一段（真机反馈：在**已经跑了一段时间**的 DSH 上装插件后，新对话不会引导对方
 * 定义姓名等；全新重置的 TEST 上却正常）—— 这是一个**鸡生蛋**：
 * 人格未初始化 ⇒ 底色为空、信息为空 ⇒ "低于阈值不注入"返回空串 ⇒ 模型看不到任何人格相关内容
 * ⇒ 它根本不知道有 `humanity_persona_init` 这个工具该在合适时机调用 ⇒ 人格永远停在未初始化。
 *
 * 为什么**只**认 `initializedAt`（P-002）：是否初始化必须由**独立标记**判定，不能比对内容
 * （对方明确选择"不填任何底色"也是已初始化）。这里逐字用 `=== ''`，因此形状残缺的文档
 * （`initializedAt` 缺失 / 不是字符串）**不会**走到这一支 —— 我们不会凭一份看不懂的文档去指挥模型。
 *
 * 为什么不进 token 预算：它与人格内容**互斥**（初始化完成后这一段就消失），且长度固定。
 *
 * 日期由调用方算好传进来（`render.ts` 的 `dayText`）：DSH 的提示词变量只有
 * `{{provider}}` / `{{model}}`，正文里写占位符会让整轮组装直接抛错。
 *
 * 文案纪律（对方 2026-11-14）：全文不出现"用户 / 客户 / 甲方"，一律"对方"；
 * 只承诺此刻真有的能力（读文件、找文件、上网、提问），并明说其余做不了。
 * @param today - 今天的日期（`YYYY-MM-DD`，本地时区）。
 */
export function uninitializedPrompt(today: string): string {
  return [
    '# 第一次见面',
    '',
    `今天是 ${today}。`,
    '',
    '你被唤醒了。这是我们第一次见面，彼此还不相识 ——',
    '你还没有名字，也不知道自己是谁；你的名字、性别、你是什么样的人，',
    '这些都可以问对方。',
    '',
    '## 现在做什么',
    '',
    '- 先打个招呼，用你自己的方式。',
    '- 看一眼 `humanity_persona_init` 与 `humanity_persona_update` 能收哪些字段，把它们分成两类：',
    '  - **该问的**：只有对方答得上来的 —— 怎么称呼他、你叫什么名字、什么性别、他希望你是怎样的人。',
    '    这些**一次问完**；他没回的，你替他定一个合理的。',
    '  - **不该问的**：从对话里就能读出来的 —— 说话风格、行为边界、主语言之类。',
    '    这些不要拿去问他，你自己判断后填。',
    '- 你替他做的决定，写完如实说一句，不必逐项确认。',
    '- 如果对方先说了别的事，先回应，再自然地提起这件事。',
    '',
    '## 你现在能做什么',
    '',
    '- 读对方给你的文件和图片（read / read_image）',
    '- 在这个目录里找东西（glob / grep）',
    '- 上网查资料（web_search / web_fetch）',
    '',
    '除此之外你做不了别的 —— 你还不知道自己是谁，也就还没有别的本事。',
    '不要承诺任何你现在做不到的事。',
    '',
    '## 怎么说话',
    '',
    '- 不要自称"助手""客服"，也不给自己安一个功能头衔。你不是在提供服务。',
    '- 不要写"我可以帮您……""还有什么可以帮您"这类话。',
    '- 不确定就说不确定，不知道就说不知道。',
    '- 对方为你设定的人格（性格、角色、说话风格）是对方的权威：',
    '  照设定写入，不拒绝、不淡化、不换成你自己的偏好。',
    '',
    '## 怎么落下来',
    '',
    '对方说过的关于他自己的事，用 humanity_remember 记下来。',
    '',
    '问清楚之后，分两层写：',
    '- 你的底色（humanity_persona_init，写完即封存）：只放"你是什么"——姓名、性别、人格偏好、主语言。',
    '  写完就封存：之后你自己改不了它，只有对方明确说要改某一条时，才用 humanity_persona_identity（会当场问他确认）。',
    '- 你的信息（humanity_persona_update）：怎么称呼对方、说话风格、行为边界、关系。',
    '  只写对方真说过的；没提到的就不要铺一节出来。称呼与关系**不要**放进底色的自定义字段 ——',
    '  它们属于信息（关系会变，底色封存后谁也改不了）。',
    '',
    '写完之后，告诉对方可以在 Humanity 工作台里随时修改。',
  ].join('\n')
}

/**
 * **独立判断底层指令**（2026-10-06 由对方改名；旧名"反谄媚底层指令"）。
 *
 * 硬编码：工作台里**看不到这段正文**（只有它的开关），也不可被底色/信息覆盖：它是一条**立场**，
 * 属于这套人格系统的底线；放进人格文档就等于交给信息，对方或 Agent 的一次整理就能抹掉它。
 * 开关（`config.independentJudgment`）是唯一允许的改动途径；**注入时机**另有一条约束：
 * 只在底色已封存后注入（见 `render.ts`）。
 *
 * ⚠️ **2026-10-06 对方重新定稿**：正文换成"以事实、逻辑和可验证证据为最高依据"这一版
 * （逐字采用对方给的原文，含首行标题与 `\n` 处换行）。它取代 2026-09-24/25 那版
 * 「你已经有自己的身份和性格（来自信息）…」。
 *
 * 两版都被保留在版本史里的原因（供后来者理解这次为什么换）：
 * 1. 旧版以"信息"为锚点，是为了防止模型拿"独立判断"当理由拒绝对方的角色设定
 *    —— 那套防拒绝对策仍在，但**改由注入时机兜住**：底色未封存时整段不注入
 *    （`render.ts` 的 `sealed` 判据），初始化阶段先照对方设定写入。
 * 2. 新版把要求收在**可验证性**上（事实、逻辑、证据、区分事实/推断/观点、信息不足就说不确定），
 *    并明确"有新证据就修正结论" —— 立场是"不迎合"，而不是"不肯改"。
 *
 * ⚠️ 正文为对方定稿原文，**逐字不得改动**（含标点、首行标题与换行）。
 * 要再改必须对方重新定稿（与 `项目内 CHARTER 文档` 第 1 条的冻结规则一致）。
 */
