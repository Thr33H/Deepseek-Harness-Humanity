/**
 * 自进化（她自己的时间）的常量。
 *
 * 与 `memory/constants.ts` 同一条纪律：**数据契约相关的字面量只在这里出现一次**
 * （文档键写进存储、任务标题写进调度、唤醒标记写进消息来源判据）。
 * @module humanity/evolution/constants
 */

/**
 * 状态文档的键（存在文档表里，与人格/时钟同一张表）。
 *
 * ⚠️ **不能等于工作台的命名空间名**（`humanity-evolution`）：0.1.7+ 的设置服务会退化成
 * "把文档写进同一张文档表"，两边用同一个键就会互相覆盖 —— 真机 2026-11-24 就这样把她的
 * 精力、次数、房间 id 全冲掉了（一次，代价是当天的记录）。
 */
export const EVOLUTION_DOC_KEY = 'humanity-evolution-state'

/**
 * 材料本子的键。
 *
 * 曾经只记"那天记过几行"（材料本身留在内存里），可内存活不过重启 —— 真机上一天重启十几次，
 * 于是"她明明说过话、日记却是空的"。现在连正文一起落盘，重启不再丢掉她的一天。
 */
export const NOTES_DOC_KEY = 'humanity-evolution-notes'

/**
 * 材料本子最多留多少行。
 *
 * 一天醒 8 次、每次几句，几十行足够；上限的意义是"这篇日记写的是这一天的近况"，
 * 不是把她一整天说的话原样搬进提示词。
 */
export const NOTES_MAX_LINES = 40

/** 她的房间在 `$DSH_HOME` 下的相对路径：她写的东西、以后的作品都落在这儿。 */
export const ROOM_DIR = 'humanity/room'

/** 房间里那个调度任务的标题（你在 DSH 的任务管理器里看到的就是它）。 */
export const ROOM_TASK_TITLE = '她自己的时间'

/**
 * 醒来提示词的标记。
 *
 * 为什么需要它：调度消息进会话时来源标记是 `schedule`，但你我也可能给自己排提醒。
 * 只有带这个标记的那条才是"她自己的时间"，其余一律不算。
 */
export const WAKE_MARKER = '[你自己的时间]'

/** 到达当日上限后，下一次排在第二天早上的几点（按她的时区）。 */
export const NEXT_MORNING_HOUR = 8

/** 排下一次的最小间隔（秒）：DSH 单任务最小投递间隔是 60 秒。 */
export const MIN_GAP_SECONDS = 60

/**
 * 房间还没排上时，隔多久借一轮对话再试一次（毫秒）。
 *
 * 为什么需要重试：真机上会话服务可能比我们挂得**晚**（store 就绪那一刻还看不见它）。
 * 装配期那一次失败如果不重试，"她没有自己的日子"就会一直停在那儿，而没人知道该等一等。
 */
export const RETRY_ARM_AFTER_MS = 2 * 60 * 1000

/**
 * 一次醒来最多带给情绪评估多少字符（她看到的东西）。
 *
 * 为什么要上限：一次醒来可能读了好几页；整段塞进评估调用会撞上下文上限，
 * 而失败的样子和没感觉一模一样。
 */
export const SEEN_LIMIT = 6000

/**
 * 她在别处说话时，房间的闹钟要一直压着，直到安静这么久（分钟）。
 *
 * 为什么需要：她只有一个身体 —— 正在跟你聊天时不该同时在自己房间里做事。
 * 这也不只是"体验"问题：两个会话同时跑，两边都会往同一份记忆与情绪上写，账会乱。
 */
export const BUSY_QUIET_MINUTES = 10

/** 检查"聊完了没有"的间隔（毫秒）。 */
export const BUSY_CHECK_MS = 60 * 1000
