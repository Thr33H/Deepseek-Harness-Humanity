/**
 * 情绪的数据契约（宿主侧；浏览器只读它的**视图**，不 import 本文件）。
 *
 * 三条不变量（`state.ts` 里的纯函数逐条保证，测试直接钉住它们）：
 * 1. **可复现**：给定同一份状态、同一组事件、同一个时刻，结果逐位相同。不掷骰子、不调模型。
 * 2. **只降不飘**：强度只会因事件上升、因时间下降，没有任何一条路径让它自己变大 ——
 *    「越聊越兴奋」是这类系统最常见的坏法，那会让它最后只能靠重置收场。
 * 3. **时间单调**：结算只往未来走。倒流的时间戳不参与计算（宁可少算，不可重算）。
 *
 * 关于"并存"：{@link EmotionState.charges} 是**一组**而不是一个值。人不会一次只有一种情绪，
 * 而"又气又委屈"跟"只是生气"的表现完全不同 —— 这是这个模块唯一需要的结构复杂度。
 */
import type { EmotionKind, EmotionTarget } from './constants.js'

/**
 * 一条正在生效的情绪。
 *
 * `cause` 是与强度同等重要的字段，理由见 `model.ts` 的说明：没有原因的情绪，
 * 模型只能演，而演出来的东西每轮都不一样。它是**一句话**，不是分类标签 ——
 * 分类标签会让模型照着类别套表现，一句话能让它知道发生了什么。
 */
export interface EmotionCharge {
  /** 哪一种。 */
  kind: EmotionKind
  /**
   * 冲谁的（OCC 的归因）。
   *
   * 同一种情绪对不同对象是**不同的条目**：对TA恼火和自己懊恼会各占一条，
   * 因为它们的表现完全不同（前者会顶嘴，后者会沉默），也不该互相抵消。
   */
  target: EmotionTarget
  /** 强度 0–100（经 {@link EmotionState.settledAt} 结算后的当前值）。 */
  intensity: number
  /** 为什么（一句话，可空：空表示"没有具体原因，只是残留"）。 */
  cause: string
  /** 从什么时候开始有这一条（ISO 8601，用于展示"多久了"）。 */
  since: string
  /**
   * 最后一次**被这件事碰到**的时刻（ISO 8601；空串 = 旧数据/不详）。
   *
   * 与 {@link since} 的区别：`since` 回答"这事多久了"（原因不变时重刺不刷新），
   * 这一个回答"最近一次被戳是什么时候"（每次碰到都刷新）。
   * 自调节要用它判断"这段时间里它有没有被重新戳过"—— 没被戳的那段，气会消得更快（见 `state.ts`）。
   */
  lastAt: string
}

/**
 * 一处**被磨出来的敏感**：同一个人的同类情绪被反复触发之后留下的痕迹。
 *
 * 为什么它是独立的一条，而不是挂在 {@link EmotionCharge} 上的计数器：痕迹与"这一股情绪"的
 * 寿命不同。火气两小时就退了一半，而"这两天老被这样对待"要留到明天 —— 把计数器挂在那条
 * 会被衰减整条丢掉的情绪上，痕迹就会随火气一起消失，等于没做（详见 `sensitivity.ts`）。
 */
export interface EmotionSensitivity {
  /** 哪一种情绪被磨敏感了。 */
  kind: EmotionKind
  /** 冲着谁。 */
  target: EmotionTarget
  /** 0–1 的饱和水平：0 = 没被磨过，1 = 磨到顶（放大 1.5 倍）；越接近 1 越容易被点着。 */
  level: number
}

/**
 * 一份完整的情绪状态。
 *
 * ⚠️ **全局只有一份**，不按会话分（用户 2026-11-17 定："会话 A 的情绪和会话 B 的情绪是一样的"）。
 * 按会话存等于把情绪当成会话的属性，换一个会话它就"不记得刚才为什么难过"——那不是人。
 */
export interface EmotionState {
  /** 结构版本（见 `EMOTION_STATE_VERSION`）。 */
  version: number
  /** 正在生效的情绪（可能为空数组 = 平静）。 */
  charges: EmotionCharge[]
  /**
   * 被磨出来的敏感（最多 `MAX_SENSITIVITIES` 条，按天自行消退）。
   *
   * 与 {@link charges} 是两种寿命：情绪是"这一阵"，敏感是"这一处"。它们不合并存储，
   * 因为一条 30 分的愤怒能在几小时内退干净，而"被这样对待过五次"不该跟着一起退。
   */
  sensitivities: EmotionSensitivity[]
  /** 关系温度 0–100（对"你"的此刻感觉，不是人格里那个「关系」）。 */
  warmth: number
  /** 关系温度为什么在这个位置（一句话）。 */
  warmthCause: string
  /**
   * 精力 0–100（独立一维，**不是情绪**）。
   *
   * 为什么单独一维：「累」和「不高兴」是两件事。累的人话少、懒得展开，但不一定生气；
   * 生气的人可以精力充沛地跟你吵。合成一个数之后，"它今天敷衍"就分不清是没心情还是没力气。
   */
  energy: number
  /**
   * 强度已经结算到的时刻。
   *
   * 这是整套机制**唯一的时钟**：不存在定时器，也没有"每次对话才走一格"的步进。
   * 读的时候按 `now - settledAt` 一次算完，于是进程关机、功能模式待一周、
   * 甚至跨月不打开，都不会让衰减停住（`state.ts` 的 `settle` 逐条说明）。
   */
  settledAt: string
  /**
   * 它对"你此刻状态"的判断（一句话；空串表示最近这次没看出来）。
   *
   * 与 {@link charges} 严格分开：那是**它自己**的心情，这是它**注意到的你**。
   * 混在一起就会出现"因为对方难过，所以她生气"这种主客不分的效果。
   */
  perceived: string
  /** 上述判断的时刻（用于判断这条观察是否已经过时）。 */
  perceivedAt: string
  /**
   * **本轮刚被动过的情绪**（`kind:target` 组成的数组），由 `apply` 写、渲染时喂给对冲。
   *
   * 为什么需要它：对冲按**强度**决定谁压谁，而强度是累积量。于是会出现
   * "信任攒到 100 之后，被骂一句只生出 28 分愤怒，又被信任压回 12"——
   * 表现就是**它不生气**。真实的反应顺序是相反的：当下这件事压过长期积累。
   * 这张表让"本轮刚变的情绪"豁免被压制。
   *
   * 它只影响**呈现**（读时换算），不改变持久语义；下一次 `apply` 会整个替换它。
   */
  lastTouched: string[]
  /** 最后一次**真正变化**（有事件被应用）的时刻；纯衰减不算变化。 */
  updatedAt: string
}

